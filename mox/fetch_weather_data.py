def fetch_hourly_24h(cities, batch_size=30):
    """获取过去24小时逐小时数据（气温、湿度、气压、降水、风速、风向）"""
    now = datetime.utcnow()
    start = (now - timedelta(hours=24)).strftime("%Y-%m-%d")
    end = now.strftime("%Y-%m-%d")

    all_rows = []
    total = len(cities)

    for i in range(0, total, batch_size):
        batch = cities[i:i + batch_size]
        lats = ",".join(str(c[1]) for c in batch)
        lons = ",".join(str(c[2]) for c in batch)

        url = "https://api.open-meteo.com/v1/forecast"
        params = {
            "latitude": lats,
            "longitude": lons,
            "hourly": HOURLY_PARAMS,
            "past_hours": 24,
            "forecast_hours": 0,
            "timezone": "Asia/Shanghai",
        }

        print(f"  获取24h数据: {i+1}-{min(i+batch_size, total)}/{total}...")
        try:
            resp = requests.get(url, params=params, timeout=60)
            resp.raise_for_status()
            data = resp.json()
        except Exception as e:
            print(f"    请求失败: {e}, 重试...")
            time.sleep(3)
            try:
                resp = requests.get(url, params=params, timeout=60)
                resp.raise_for_status()
                data = resp.json()
            except Exception as e2:
                print(f"    重试失败: {e2}, 跳过此批次")
                continue

        if isinstance(data, list):
            results = data
        else:
            results = [data]

        for j, city_data in enumerate(results):
            city_name = batch[j][0]
            hourly = city_data.get("hourly", {})
            times = hourly.get("time", [])
            for t_idx, ts in enumerate(times):
                row = {"城市": city_name, "时间": ts}
                for param in HOURLY_PARAMS.split(","):
                    vals = hourly.get(param, [])
                    row[PARAM_CN.get(param, param)] = vals[t_idx] if t_idx < len(vals) else None
                all_rows.append(row)

        time.sleep(0.5)

    return pd.DataFrame(all_rows)


def fetch_yearly_daily(cities, batch_size=30):
    """获取过去一年逐日气温数据"""
    now = datetime.utcnow()
    end_date = (now - timedelta(days=5)).strftime("%Y-%m-%d")
    start_date = (now - timedelta(days=365)).strftime("%Y-%m-%d")

    all_rows = []
    total = len(cities)

    for i in range(0, total, batch_size):
        batch = cities[i:i + batch_size]
        lats = ",".join(str(c[1]) for c in batch)
        lons = ",".join(str(c[2]) for c in batch)

        url = "https://archive-api.open-meteo.com/v1/archive"
        params = {
            "latitude": lats,
            "longitude": lons,
            "daily": DAILY_PARAMS,
            "start_date": start_date,
            "end_date": end_date,
            "timezone": "Asia/Shanghai",
        }

        print(f"  获取年度数据: {i+1}-{min(i+batch_size, total)}/{total}...")
        try:
            resp = requests.get(url, params=params, timeout=120)
            resp.raise_for_status()
            data = resp.json()
        except Exception as e:
            print(f"    请求失败: {e}, 重试...")
            time.sleep(5)
            try:
                resp = requests.get(url, params=params, timeout=120)
                resp.raise_for_status()
                data = resp.json()
            except Exception as e2:
                print(f"    重试失败: {e2}, 跳过此批次")
                continue

        if isinstance(data, list):
            results = data
        else:
            results = [data]

        for j, city_data in enumerate(results):
            city_name = batch[j][0]
            daily = city_data.get("daily", {})
            times = daily.get("time", [])
            for t_idx, ts in enumerate(times):
                row = {"城市": city_name, "日期": ts}
                for param in DAILY_PARAMS.split(","):
                    vals = daily.get(param, [])
                    row[PARAM_CN.get(param, param)] = vals[t_idx] if t_idx < len(vals) else None
                all_rows.append(row)

        time.sleep(1)

    return pd.DataFrame(all_rows)


